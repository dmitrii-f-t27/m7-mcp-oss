/**
 * The name lists of the path rules, and the generator of specs/path_tables.t27 from them.
 *
 *   node specs/tables/path_tables.mjs [root]     writes root/specs/path_tables.t27 (specs/generate.sh does this)
 *
 * The four lists are the lists of src/core/security/pathGuard.ts at c41f8ce, unchanged. Each name is folded
 * text (see foldName there): lower case, no look-alike letters, no ignorable marks, no trailing dots or
 * spaces. tests/rulesPath.test.mjs checks them against the old pathGuard.ts.
 *
 * A spec cannot call another spec with an array, so path_tables.t27 holds the names as one byte table and
 * answers with scalars: how many names a table has, where a name starts and ends in the byte table, and the
 * byte at a place. specs/path_rules.t27 compares a path segment with these names byte by byte.
 */

import { mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

/** Names (whole path segment, folded) that hold secrets. */
export const SECRET_NAMES = [
  '.env', '.envrc', '.npmrc', '.netrc', '.pypirc', '.pgpass', '.git-credentials',
  'id_rsa', 'id_dsa', 'id_ecdsa', 'id_ed25519',
  'credentials', '.aws', '.ssh', '.docker', '.kube', '.gnupg',
];
/** A segment that starts with one of these holds secrets (`.env.local`). */
export const SECRET_PREFIXES = ['.env.'];
/** A segment that ends with one of these holds secrets. */
export const SECRET_SUFFIXES = ['.key', '.pem', '.p12', '.pfx', '.jks', '.keystore', '.env'];
/** Names (whole path segment, folded) that steer git, editors, agents or M7. */
export const CONTROL_NAMES = [
  '.git', '.cursor', '.cursorrules', '.vscode', '.claude', '.m7', '.husky', '.github', '.mcp.json',
  'claude.md', 'agents.md', 'gemini.md', '.clinerules', '.windsurfrules', '.devcontainer', '.idea',
  '.gitmodules', '.gitattributes',
];

/** The tables in the order of their numbers in the spec. */
export const TABLES = [
  ['SECRET_NAMES', SECRET_NAMES],
  ['SECRET_PREFIXES', SECRET_PREFIXES],
  ['SECRET_SUFFIXES', SECRET_SUFFIXES],
  ['CONTROL_NAMES', CONTROL_NAMES],
];

const NOTICE = '// Added by Dmitrii Fedorov, 2026; not part of the original M7 MCP. Apache-2.0 (see NOTICE).';

function check() {
  for (const [name, list] of TABLES) {
    if (list.length === 0) throw new Error(`${name} is empty`);
    if (new Set(list).size !== list.length) throw new Error(`${name} names a name twice`);
    for (const entry of list) {
      if (entry === '' || !/^[\x21-\x7e]+$/.test(entry)) throw new Error(`${name}: "${entry}" must be printable ASCII without spaces and not empty`);
      if (entry !== entry.toLowerCase()) throw new Error(`${name}: "${entry}" is not lower case (the lists hold folded text)`);
    }
  }
}

const wrap = (numbers, per) => {
  const lines = [];
  for (let i = 0; i < numbers.length; i += per) lines.push(`    ${numbers.slice(i, i + per).join(', ')}`);
  return lines.join(',\n');
};

/** The text of specs/path_tables.t27. */
export function renderPathTables() {
  check();
  const entries = TABLES.flatMap(([, list]) => list);
  const bytes = [];
  const bounds = [];
  for (const entry of entries) {
    bounds.push(bytes.length);
    for (const c of entry) bytes.push(c.charCodeAt(0));
  }
  bounds.push(bytes.length);
  const first = [0];
  for (const [, list] of TABLES) first.push(first[first.length - 1] + list.length);
  const ids = TABLES.map(([name], i) => `pub const PT_${name} : i32 = ${i};`).join('\n');
  return `${NOTICE}
; Name tables of the path rules. GENERATED by specs/tables/path_tables.mjs from the name lists of
; src/core/security/pathGuard.ts at c41f8ce. Do not edit this file: change the lists in
; specs/tables/path_tables.mjs and run specs/generate.sh.
; Cross-spec calls take scalars only, so the names are one byte table and the functions below answer
; with numbers: how many names table t has (pt_count), where name i of table t starts and ends in the
; byte table (pt_start, pt_end) and the byte at a place (pt_byte). A wrong table or index answers -1.
module PathTables;

${ids}
pub const PT_TABLES : i32 = ${TABLES.length};
pub const PT_ENTRIES : i32 = ${entries.length};
pub const PT_BYTES_LEN : i32 = ${bytes.length};

; The names one after the other, without separators.
pub const PT_BYTES : [${bytes.length}]u8 = [
${wrap(bytes, 20)}
];

; Where each name starts in PT_BYTES; the last entry is the end of the last name.
pub const PT_BOUNDS : [${bounds.length}]i32 = [
${wrap(bounds, 20)}
];

; The index of the first name of each table in PT_BOUNDS; the last entry is PT_ENTRIES.
pub const PT_FIRST : [${first.length}]i32 = [${first.join(', ')}];

pub fn pt_count(t: i32) -> i32 {
    if (t < 0 or t >= PT_TABLES) { return 0; }
    return PT_FIRST[t + 1] - PT_FIRST[t];
}

pub fn pt_start(t: i32, i: i32) -> i32 {
    if (i < 0 or i >= pt_count(t)) { return -1; }
    return PT_BOUNDS[PT_FIRST[t] + i];
}

pub fn pt_end(t: i32, i: i32) -> i32 {
    if (i < 0 or i >= pt_count(t)) { return -1; }
    return PT_BOUNDS[PT_FIRST[t] + i + 1];
}

pub fn pt_byte(p: i32) -> u8 {
    if (p < 0 or p >= PT_BYTES_LEN) { return 0; }
    return PT_BYTES[p];
}

test pt_tables_shape {
    assert pt_count(PT_SECRET_NAMES) == ${SECRET_NAMES.length};
    assert pt_count(PT_SECRET_PREFIXES) == ${SECRET_PREFIXES.length};
    assert pt_count(PT_SECRET_SUFFIXES) == ${SECRET_SUFFIXES.length};
    assert pt_count(PT_CONTROL_NAMES) == ${CONTROL_NAMES.length};
    assert pt_count(-1) == 0;
    assert pt_count(PT_TABLES) == 0;
    assert pt_start(PT_SECRET_NAMES, 0) == 0;
    assert pt_end(PT_SECRET_NAMES, 0) == ${SECRET_NAMES[0].length};
    assert pt_start(PT_SECRET_NAMES, -1) == -1;
    assert pt_start(PT_SECRET_NAMES, ${SECRET_NAMES.length}) == -1;
    assert pt_end(PT_CONTROL_NAMES, ${CONTROL_NAMES.length}) == -1;
    assert pt_end(PT_CONTROL_NAMES, ${CONTROL_NAMES.length - 1}) == PT_BYTES_LEN;
    assert pt_byte(0) == ${SECRET_NAMES[0].charCodeAt(0)};
    assert pt_byte(-1) == 0;
    assert pt_byte(PT_BYTES_LEN) == 0;
}
`;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const root = path.resolve(process.argv[2] ?? path.join(path.dirname(fileURLToPath(import.meta.url)), '..', '..'));
  mkdirSync(path.join(root, 'specs'), { recursive: true });
  writeFileSync(path.join(root, 'specs', 'path_tables.t27'), renderPathTables());
  console.log('specs/path_tables.t27: written');
}
